async function main() {
    console.log('Translating account names to Arabic...');
    for (const [code, name] of Object.entries(TRANSLATIONS)) {
        await prisma.account.updateMany({
            where: { code },
            data: { name }
        });
        console.log(`Updated ${code} -> ${name}`);
    }
    console.log('Done!');
}

